    c = act(cid, name, event("throw", when), L, pri=pri, file=FR, blend_in=0.04)
    strike(c, "right_arm", Z, arm('r', *wind), arm('r', *release), arm('r', *follow), 0.18, 0.26, 0.38, L)
    strike(c, "body", Z, tilt(*body_w), tilt(*body_r), tilt(*body_r), 0.18, 0.26, 0.38, L)
    c.rot("left_arm", (0, Z), (0.18, arm('l', 60, 20)), (0.26, arm('l', -20, 10)), (L, Z))
    if legs:
        c.rot("right_leg", (0, Z), (0.18, leg('r', *legs[0])), (0.26, leg('r', *legs[1])), (L, Z))
    c.ev(0.22, "whoosh", weight="light")
    return c


