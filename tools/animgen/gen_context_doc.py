#!/usr/bin/env python3
"""Generates docs/CONTEXT_VARIABLES.md from the Java sources, so the reference cannot drift from the code.

For every context variable declared in CtxVars.java it lists the section, the Java constant, and the exact
expression(s) the samplers assign to it; engine variables declared elsewhere (q.anim_time, q.event_dir ...)
are listed with the class that owns them. Run: python3 tools/animgen/gen_context_doc.py [--check]
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
JAVA = os.path.join(ROOT, "src/main/java")
CTX = os.path.join(JAVA, "com/motionworks/common/CtxVars.java")
OUT = os.path.join(ROOT, "docs/CONTEXT_VARIABLES.md")

KIND = {"set": "number", "setBool": "0 / 1", "setString": "string id"}

INTRO = """# Context variables

Animation expressions (trigger conditions, `stop_when`, weights and keyframe values) read the entity's
situation through `q.*` variables. Clients sample them every tick in `ContextSampler` (and a few in
`EntityAnimator` and `SocialDirector`); clips may only use names listed here, which the authoring
validator (`tools/animgen/build.py --check`) and `SourceConventionsTest` enforce.

Conventions: speeds are blocks per tick, angles degrees, times seconds, distances blocks. Flags are 0 or 1.
String variables hold an interned id and compare with `==` against a quoted name, e.g.
`q.feet_block == 'cobweb'`. Unset variables read 0.

This file is generated by `tools/animgen/gen_context_doc.py` from the Java sources; the "assigned from"
column is the code that computes the value.
"""


def read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def java_sources():
    for dirpath, _, files in os.walk(JAVA):
        for fn in sorted(files):
            if fn.endswith(".java"):
                path = os.path.join(dirpath, fn)
                yield os.path.relpath(path, JAVA), read(path)


def call_args(src, start):
    """The argument text of the call whose opening parenthesis is at src[start]."""
    depth, i = 0, start
    while i < len(src):
        ch = src[i]
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                return src[start + 1:i]
        elif ch == '"':
            i = src.index('"', i + 1)
        i += 1
    return src[start + 1:]


def declared():
    section, out = "General", []
    for line in read(CTX).split("\n"):
        m = re.match(r"\s*// (.+)", line)
        if m:
            section = m.group(1).strip()
        m = re.search(r'int (\w+) = Vars\.id\("([^"]+)"\)', line)
        if m:
            out.append((section, m.group(1), m.group(2)))
    return out


def definition(src, expr):
    """Follows a bare local (or a history field h.x) to the expression that defines it in the same file."""
    m = re.fullmatch(r"(?:\(float\) )?(h\.)?(\w+)", expr)
    if not m:
        return expr
    name = m.group(2)
    if m.group(1):
        d = re.search(r"\bh\." + name + r"\s*(=|\+=|-=)\s*([^;]+);", src)
    else:
        d = re.search(r"\b(?:float|double|boolean|int|long|String|var)\s+" + name + r"\s*=\s*([^;]+);", src)
    if not d:
        return expr
    body = " ".join(d.group(d.lastindex).split())
    op = d.group(1) if m.group(1) else "="
    return "%s %s %s" % (expr, op, body if len(body) < 140 else body[:137] + "...")


def assignments(sources):
    found = {}
    for rel, src in sources:
        for m in re.finditer(r"\.(set|setBool|setString)\(\s*CtxVars\.(\w+)\s*,", src):
            args = call_args(src, m.end(0) - len(m.group(0)) + len(m.group(1)) + 1)
            expr = definition(src, " ".join(args.split(",", 1)[1].split()))
            found.setdefault(m.group(2), []).append((m.group(1), expr, os.path.basename(rel)))
    return found


def engine_vars(sources, ctx_names):
    out = {}
    for rel, src in sources:
        if rel.endswith("CtxVars.java"):
            continue
        for name in re.findall(r'\bid\("(q\.[a-z0-9_]+)"\)', src):
            if name not in ctx_names:
                out.setdefault(name, set()).add(os.path.basename(rel).replace(".java", ""))
    return out


def render():
    sources = list(java_sources())
    decl = declared()
    sets = assignments(sources)
    lines = [INTRO]
    current = None
    for section, const, name in decl:
        if section != current:
            current = section
            lines += ["", "## " + section, "", "| Variable | Type | Assigned from |", "|---|---|---|"]
        uses = sets.get(const, [])
        kind = ", ".join(sorted({KIND[k] for k, _, _ in uses})) or "-"
        how = "<br>".join("`%s` (%s)" % (e.replace("|", "\\|"), f) for _, e, f in uses[:3]) or "not assigned"
        lines.append("| `%s` | %s | %s |" % (name, kind, how))
    eng = engine_vars(sources, {n for _, _, n in decl})
    lines += ["", "## Engine and playback variables", "",
              "Set by the animation runtime rather than the context sampler.", "", "| Variable | Owner |", "|---|---|"]
    for name in sorted(eng):
        lines.append("| `%s` | %s |" % (name, ", ".join(sorted(eng[name]))))
    lines.append("")
    return "\n".join(lines), len(decl), len(eng)


def main():
    text, n_ctx, n_eng = render()
    if "--check" in sys.argv:
        current = read(OUT) if os.path.exists(OUT) else ""
        if current != text:
            print("docs/CONTEXT_VARIABLES.md is out of date; run tools/animgen/gen_context_doc.py")
            sys.exit(1)
        print("context variable reference is up to date")
        return
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote docs/CONTEXT_VARIABLES.md: %d context variables, %d engine variables" % (n_ctx, n_eng))


if __name__ == "__main__":
    main()
